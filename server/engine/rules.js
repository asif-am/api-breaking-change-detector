export const RULES = DEFINITIONS.map((rule, index) => ({
  ...rule,
  id: `R-${String(index + 1).padStart(2, '0')}`,
}));

const RULE_BY_CODE = new Map(RULES.map((rule) => [rule.code, rule]));

export function getRule(code) {
  const rule = RULE_BY_CODE.get(code);
  if (!rule) {
    throw new Error(`Unknown comparison rule: ${code}`);
  }
  return rule;
}

export function ruleSummary() {
  return RULES.map(({ id, code, category, classification, severity, title }) => ({
    id,
    code,
    category,
    classification,
    severity,
    title,
  }));
}

